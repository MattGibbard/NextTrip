/** How an airport reads in a list of choices: "London (any airport)", "Manchester (MAN)". */
export function airportChoice(row: MainAirportRow): string {
  return row[5] === "any" ? `${row[1]} (any airport)` : `${row[1]} (${row[0]})`;
}

/** The countries to group a list of choices by, with the country of `code` (where they fly from now) first. */
export function airportGroups(code: string): [string, string][] {
  const mine = mainAirport(code)?.[2];
  return Object.entries(AIRPORT_COUNTRIES).sort(([a], [b]) => Number(b === mine) - Number(a === mine));
}

export function mainAirport(code: string | null | undefined): MainAirportRow | undefined {
  return code ? MAIN_AIRPORTS.find((r) => r[0] === code) : undefined;
}

/** An airport from the list as a From, with prices in `currency` (by default its own country's). */
export function airportFrom(row: MainAirportRow, currency = currencyFor(row[2])): From {
  return { code: row[0], name: row[1], lat: row[3], lon: row[4], currency };
}

/**
 * The airport someone in `country` at a rough position most likely flies from: the nearest in their
 * own country, so a visitor near a border isn't sent abroad, or the nearest anywhere when the list has
 * none for their country. Without a position, their country's first (main) airport.
 */
export function nearestMainAirport(country: string | null, lat: number | null, lon: number | null): MainAirportRow | undefined {
  const pickable = MAIN_AIRPORTS.filter((r) => r[5] !== "far");
  const home = country ? pickable.filter((r) => r[2] === country) : [];
  if (lat === null || lon === null) return home[0];
  const rows = home.length ? home : pickable;
  const squash = Math.cos((lat * Math.PI) / 180);
  let best: MainAirportRow | undefined;
  let bestD = Infinity;
  for (const r of rows) {
    const d = (r[3] - lat) ** 2 + ((r[4] - lon) * squash) ** 2;
    if (d < bestD) [best, bestD] = [r, d];
  }
  return best;
}
